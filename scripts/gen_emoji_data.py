"""Regenerate desktop/emoji-data.js (ticket 385) from the MIT-licensed npm package unicode-emoji-json.

    npm pack unicode-emoji-json@0.9.0 && tar xzf unicode-emoji-json-0.9.0.tgz
    python -I scripts/gen_emoji_data.py package/data-by-group.json desktop/emoji-data.js

Only emoji up to Emoji 15.0 are kept, because Windows' Segoe UI Emoji draws nothing newer.
The chat window's CSP allows scripts from 'self' only, so the list ships as a local file.
"""
import json, sys

ZH = {'smileys_emotion': '表情', 'people_body': '人物', 'animals_nature': '动物与自然', 'food_drink': '食物',
      'travel_places': '旅行与地点', 'activities': '活动', 'objects': '物品', 'symbols': '符号', 'flags': '旗帜'}
MAX_VERSION = 15.0

def main(source, target):
    groups = json.load(open(source, encoding='utf-8'))
    out = []
    for group in groups:
        if group['slug'] not in ZH: continue
        items = [[e['emoji'], e['name']] for e in group['emojis'] if float(e['emoji_version']) <= MAX_VERSION]
        out.append([ZH[group['slug']], items])
    body = json.dumps(out, ensure_ascii=False, separators=(',', ':'))
    with open(target, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('// Generated by scripts/gen_emoji_data.py from unicode-emoji-json 0.9.0 (MIT). Do not edit by hand.\n')
        handle.write('window.VEIL_EMOJI=' + body + ';\n')
    print(sum(len(g[1]) for g in out), 'emoji in', len(out), 'groups')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
