'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('veilDesktop', {
  request: (path, body, timeoutMs) => ipcRenderer.invoke('chat:request', path, body, timeoutMs),
  reconnect: () => ipcRenderer.invoke('chat:reconnect'),
  copyText: text => ipcRenderer.invoke('chat:copy-text', text),
  mediaUrl: filename => ipcRenderer.invoke('chat:media-url', filename),
  stickerUrl: filename => ipcRenderer.invoke('chat:sticker-url', filename),
  attachmentText: id => ipcRenderer.invoke('chat:attachment-text', id),
  openAttachment: id => ipcRenderer.invoke('chat:open-attachment', id),
  petSize: () => ipcRenderer.invoke('chat:pet-size'),
  setPetSize: size => ipcRenderer.invoke('chat:set-pet-size', size),
  saveTheme: theme => ipcRenderer.invoke('chat:save-theme', theme),
  getVisualTheme: () => ipcRenderer.invoke('chat:get-visual-theme'),
  onThemeChanged: callback => ipcRenderer.on('theme:changed', (_event, payload) => callback(payload)),
  getAvatar: () => ipcRenderer.invoke('chat:get-avatar'),
  saveAvatar: dataUrl => ipcRenderer.invoke('chat:save-avatar', dataUrl),
  clearAvatar: () => ipcRenderer.invoke('chat:clear-avatar'),
  onAvatarChanged: callback => ipcRenderer.on('avatar:changed', (_event, dataUrl) => callback(dataUrl)),
  getCustomCss: () => ipcRenderer.invoke('chat:get-custom-css'),
  saveCustomCss: cssText => ipcRenderer.invoke('chat:save-custom-css', cssText),
  resetCustomCss: () => ipcRenderer.invoke('chat:reset-custom-css'),
  openCustomCss: () => ipcRenderer.invoke('chat:open-custom-css'),
  onCustomCssChanged: callback => ipcRenderer.on('custom-css:changed', (_event, cssText) => callback(cssText)),
  chooseFolder: () => ipcRenderer.invoke('chat:choose-folder'),
  chooseBackground: () => ipcRenderer.invoke('chat:choose-background'),
  getBackground: () => ipcRenderer.invoke('chat:get-background'),
  clearBackground: () => ipcRenderer.invoke('chat:clear-background'),
  collapse: () => ipcRenderer.send('desktop:collapse'),
  expand: () => ipcRenderer.send('desktop:expand'),
  openNowhere: url => ipcRenderer.invoke('chat:open-nowhere', url),
  openMaintenance: url => ipcRenderer.invoke('chat:open-maintenance', url),
  detachView: (view, point) => ipcRenderer.invoke('view:detach', view, point),
  mergeView: view => ipcRenderer.invoke('view:merge', view),
  focusView: view => ipcRenderer.invoke('view:focus', view),
  getPinned: view => ipcRenderer.invoke('view:get-pinned', view),
  setPinned: (view, pinned) => ipcRenderer.invoke('view:set-pinned', view, pinned),
  onPinnedState: callback => ipcRenderer.on('view:pinned-state', (_event, pinned) => callback(pinned)),
  openLifeRecord: id => ipcRenderer.invoke('life:open-record', id),
  onOpenLifeRecord: callback => ipcRenderer.on('desktop:open-life-record', (_event, id) => callback(id)),
  detachedViews: () => ipcRenderer.invoke('view:states'),
  onDetachedViews: callback => ipcRenderer.on('view:states', (_event, views) => callback(views)),
  onShowActivity: callback => ipcRenderer.on('desktop:show-activity', () => callback()),
  onShowView: callback => ipcRenderer.on('desktop:show-view', (_event, view) => callback(view)),
  onShowSettings: callback => ipcRenderer.on('desktop:show-settings', () => callback())
});
